import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const currentDirectory = path.dirname(fileURLToPath(import.meta.url));
const databaseDirectory = path.resolve(currentDirectory, '..');
const sourceDirectory = path.join(databaseDirectory, 'sources');
const sourcePath = path.join(sourceDirectory, 'xuan-huong-old-wards.arcgis.geojson');
const migrationPath = path.join(databaseDirectory, 'migrations', '004_xuan_huong_old_wards.sql');

const itemId = '64bc0640738f4256896c73816c3665b5';
const itemUrl = `https://www.arcgis.com/sharing/rest/content/items/${itemId}?f=json`;
const layerUrl = 'https://services8.arcgis.com/p9AYirapk3vVPTbb/arcgis/rest/services/3rd_Level_Administrative_Boundaries_Vietnam/FeatureServer/0';
const wantedFids = [5484, 5487, 5488, 5489, 5490];
const wantedWards = ['1', '2', '3', '4', '10'];

async function getJson(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'DataForLife-CSKV/0.1 boundary-reconstruction' } });
  if (!response.ok) throw new Error(`Cannot download ${url}: HTTP ${response.status}`);
  return response.json();
}

const query = new URL(`${layerUrl}/query`);
query.search = new URLSearchParams({
  f: 'geojson',
  where: `FID IN (${wantedFids.join(',')})`,
  outFields: 'FID,NAME_1,NAME_2,NAME_3,TYPE_3',
  returnGeometry: 'true',
  outSR: '4326',
}).toString();

const [item, downloaded] = await Promise.all([getJson(itemUrl), getJson(query)]);
const features = [...(downloaded.features ?? [])].sort(
  (left, right) => Number(left.properties.NAME_3) - Number(right.properties.NAME_3),
);
const names = features.map((feature) => String(feature.properties.NAME_3));
if (features.length !== 5 || wantedWards.some((ward) => !names.includes(ward))) {
  throw new Error(`Expected old wards ${wantedWards.join(', ')}, received ${names.join(', ') || 'none'}`);
}
for (const feature of features) {
  if (feature.properties.NAME_1 !== 'Lâm Đồng' || feature.properties.NAME_2 !== 'Đà Lạt') {
    throw new Error(`Unexpected source feature ${JSON.stringify(feature.properties)}`);
  }
}

const source = {
  type: 'FeatureCollection',
  name: 'Historical wards 1, 2, 3, 4 and 10 of former Đà Lạt city',
  source: {
    itemId,
    title: item.title,
    url: item.url,
    itemUrl: `https://www.arcgis.com/home/item.html?id=${itemId}`,
    datasetDescription: item.description || null,
    dataVintage: 'Global Administrative Areas 2015 (v2.8)',
    retrievedAt: new Date().toISOString(),
  },
  features,
};

await fs.mkdir(sourceDirectory, { recursive: true });
await fs.writeFile(sourcePath, `${JSON.stringify(source, null, 2)}\n`, 'utf8');

const embeddedGeoJson = JSON.stringify({ type: 'FeatureCollection', features });
const generatedAt = new Date().toISOString();
const migration = `-- Generated by database/tools/generate-xuan-huong-service-areas.mjs
-- Source: ${source.source.itemUrl}
-- Generated: ${generatedAt}
-- These are reference reconstructions of five former wards, not approved CSKV boundaries.

BEGIN;

WITH source_document AS (
  SELECT $geojson$${embeddedGeoJson}$geojson$::jsonb AS doc
), source_features AS (
  SELECT
    feature->'properties'->>'NAME_3' AS legacy_ward_code,
    (feature->'properties'->>'FID')::integer AS source_fid,
    ST_Multi(
      ST_SetSRID(ST_GeomFromGeoJSON(feature->'geometry'), 4326)
    )::geometry(MultiPolygon, 4326) AS source_geom
  FROM source_document,
       LATERAL jsonb_array_elements(doc->'features') AS feature
), parent AS (
  SELECT l.id AS locality_id, b.geom
  FROM localities l
  JOIN boundaries b ON b.locality_id = l.id
  WHERE l.code = '24781'
), clipped AS (
  SELECT
    s.legacy_ward_code,
    s.source_fid,
    s.source_geom,
    ST_Multi(
      ST_CollectionExtract(
        ST_MakeValid(ST_Intersection(s.source_geom, p.geom)),
        3
      )
    )::geometry(MultiPolygon, 4326) AS geom
  FROM source_features s
  CROSS JOIN parent p
), covered AS (
  SELECT ST_UnaryUnion(ST_Collect(geom)) AS geom
  FROM clipped
), gap_dump AS (
  SELECT (
    ST_Dump(
      ST_CollectionExtract(ST_Difference(p.geom, c.geom), 3)
    )
  ).geom AS geom
  FROM parent p
  CROSS JOIN covered c
), gap_parts AS (
  SELECT
    row_number() OVER (
      ORDER BY ST_X(ST_PointOnSurface(geom)), ST_Y(ST_PointOnSurface(geom))
    ) AS gap_id,
    geom
  FROM gap_dump
), ranked_gaps AS (
  SELECT
    g.gap_id,
    g.geom,
    c.legacy_ward_code,
    row_number() OVER (
      PARTITION BY g.gap_id
      ORDER BY
        ST_Length(
          ST_Intersection(ST_Boundary(g.geom), ST_Boundary(c.geom))::geography
        ) DESC,
        ST_Distance(ST_PointOnSurface(g.geom)::geography, c.geom::geography),
        c.legacy_ward_code::integer
    ) AS priority
  FROM gap_parts g
  CROSS JOIN clipped c
), assigned_gaps AS (
  SELECT legacy_ward_code, ST_UnaryUnion(ST_Collect(geom)) AS geom
  FROM ranked_gaps
  WHERE priority = 1
  GROUP BY legacy_ward_code
), reconstructed AS (
  SELECT
    c.legacy_ward_code,
    c.source_fid,
    c.source_geom,
    ST_Multi(
      ST_CollectionExtract(
        ST_MakeValid(
          ST_UnaryUnion(ST_Collect(c.geom, a.geom))
        ),
        3
      )
    )::geometry(MultiPolygon, 4326) AS geom
  FROM clipped c
  LEFT JOIN assigned_gaps a USING (legacy_ward_code)
), labels(legacy_ward_code, group_name, description, display_color, display_order) AS (
  VALUES
    ('1', 'Trung tâm lõi', 'Khu vực thuộc địa giới Phường 1 cũ.', '#1D6F8A', 1),
    ('2', 'Trung tâm lõi', 'Khu vực thuộc địa giới Phường 2 cũ.', '#3A7D44', 2),
    ('3', 'Phía Nam và nghỉ dưỡng', 'Khu vực thuộc địa giới Phường 3 cũ.', '#7A5AA6', 3),
    ('4', 'Phía Nam và nghỉ dưỡng', 'Khu vực thuộc địa giới Phường 4 cũ.', '#B36A2E', 4),
    ('10', 'Phía Đông và Trại Hầm', 'Khu vực thuộc địa giới Phường 10 cũ.', '#5C6F91', 5)
)
INSERT INTO service_areas (
  locality_id,
  code,
  name,
  legacy_ward_code,
  group_name,
  description,
  display_color,
  display_order,
  area_km2,
  geom,
  label_geom,
  is_demo,
  visibility,
  provenance_status,
  source_system,
  source_id,
  source_url,
  source_version,
  raw_source
)
SELECT
  p.locality_id,
  'XH-P' || r.legacy_ward_code,
  'Khu vực Phường ' || r.legacy_ward_code || ' cũ',
  r.legacy_ward_code,
  d.group_name,
  d.description,
  d.display_color,
  d.display_order,
  round((ST_Area(r.geom::geography) / 1000000)::numeric, 4),
  r.geom,
  ST_PointOnSurface(r.geom),
  true,
  'public',
  'reference_reconstructed',
  'arcgis-gadm-reference',
  'arcgis-fid-' || r.source_fid,
  'https://www.arcgis.com/home/item.html?id=${itemId}',
  'Global Administrative Areas 2015 (v2.8); reconciled to locality 24781',
  jsonb_build_object(
    'source_fid', r.source_fid,
    'legacy_ward_code', r.legacy_ward_code,
    'source_area_km2', round((ST_Area(r.source_geom::geography) / 1000000)::numeric, 6),
    'reconstruction_method', 'clip source ward; assign uncovered parent slivers by shared-boundary length and nearest distance',
    'is_approved_cskv_boundary', false
  )
FROM reconstructed r
JOIN labels d USING (legacy_ward_code)
CROSS JOIN parent p
ON CONFLICT (code) DO UPDATE SET
  locality_id = EXCLUDED.locality_id,
  name = EXCLUDED.name,
  legacy_ward_code = EXCLUDED.legacy_ward_code,
  group_name = EXCLUDED.group_name,
  description = EXCLUDED.description,
  display_color = EXCLUDED.display_color,
  display_order = EXCLUDED.display_order,
  area_km2 = EXCLUDED.area_km2,
  geom = EXCLUDED.geom,
  label_geom = EXCLUDED.label_geom,
  is_demo = EXCLUDED.is_demo,
  visibility = EXCLUDED.visibility,
  provenance_status = EXCLUDED.provenance_status,
  source_system = EXCLUDED.source_system,
  source_id = EXCLUDED.source_id,
  source_url = EXCLUDED.source_url,
  source_version = EXCLUDED.source_version,
  raw_source = EXCLUDED.raw_source,
  updated_at = now();

DO $validation$
DECLARE
  parent_geom geometry(MultiPolygon, 4326);
  union_geom geometry;
  sum_area double precision;
  symmetric_difference_m2 double precision;
  overlap_m2 double precision;
  zone_count integer;
BEGIN
  SELECT b.geom INTO parent_geom
  FROM boundaries b
  JOIN localities l ON l.id = b.locality_id
  WHERE l.code = '24781';

  SELECT
    count(*),
    ST_UnaryUnion(ST_Collect(sa.geom)),
    sum(ST_Area(sa.geom::geography))
  INTO zone_count, union_geom, sum_area
  FROM service_areas sa
  JOIN localities l ON l.id = sa.locality_id
  WHERE l.code = '24781' AND sa.code LIKE 'XH-P%';

  symmetric_difference_m2 := ST_Area(ST_SymDifference(parent_geom, union_geom)::geography);
  overlap_m2 := sum_area - ST_Area(union_geom::geography);

  IF zone_count <> 5 THEN
    RAISE EXCEPTION 'Expected 5 Xuân Hương service areas, found %', zone_count;
  END IF;
  IF EXISTS (
    SELECT 1 FROM service_areas sa
    JOIN localities l ON l.id = sa.locality_id
    WHERE l.code = '24781' AND sa.code LIKE 'XH-P%' AND NOT ST_IsValid(sa.geom)
  ) THEN
    RAISE EXCEPTION 'A Xuân Hương service area has invalid geometry';
  END IF;
  IF symmetric_difference_m2 > 1 OR abs(overlap_m2) > 1 THEN
    RAISE EXCEPTION 'Xuân Hương topology failed: symmetric difference % m2, overlap % m2',
      symmetric_difference_m2, overlap_m2;
  END IF;
END
$validation$;

COMMIT;
`;

await fs.writeFile(migrationPath, migration, 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), sourcePath)}`);
console.log(`Wrote ${path.relative(process.cwd(), migrationPath)}`);
